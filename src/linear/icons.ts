// setting it on a scratch project in Example Workspace on 2026-10-10. Emoji
// shortcodes (`:rocket:`) are accepted too; raw emoji (`🚀`) are not.
//
// Names that look plausible but Linear rejected, so callers do not reach for
// them: Map, Document, Gear, Settings, Cog, Code, Star, Flag, Key, Globe,
// Lightbulb, Mail, Pencil, Puzzle, Tag, Target, Tools, Trophy, Clock, Gift,
// Note, List, Layers, Package, Sparkle, Warning, Info, Check, Git, Branch.
// Closest accepted stand-ins: World (for Map), Page (for Document), Favorite
